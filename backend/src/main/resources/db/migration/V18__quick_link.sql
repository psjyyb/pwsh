-- =====================================================================
-- V18 — 자주찾는 서비스 (CMS 1.2.45, CMS의 V22 — 예시 4개만 이 저장소 것)
--
-- 사용자 메인 히어로 바로 아래의 바로가기 버튼(사용자 결정: 히어로 아래 · 아이콘은 메뉴 아이콘 목록에서 고른다 — 파일 없음).
-- 한 행 = 버튼 하나. 순서는 ▲▼(인접 교환)로만 바꾼다(배너·팝업과 같은 방식).
-- display_yn(노출)과 use_yn(삭제)을 나눈다 — 잠시 내린 버튼은 순서 자리를 지켜, 다시 켜면 원래 자리로 돌아온다.
-- ★ link_url은 그대로 링크(href)가 된다 — 서비스가 '/'로 시작하는 사이트 안 경로나 http(s)://만 받는다(javascript:·//다른사이트 차단).
-- =====================================================================

CREATE TABLE IF NOT EXISTS quick_link (
    quick_link_id INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(50)  NOT NULL,
    link_url      VARCHAR(255) NOT NULL,
    icon          VARCHAR(30),
    target_yn     VARCHAR(1)   NOT NULL DEFAULT 'N',
    display_yn    VARCHAR(1)   NOT NULL DEFAULT 'Y',
    sort_no       INTEGER,
    use_yn        VARCHAR(1)   NOT NULL DEFAULT 'Y',
    reg_id        VARCHAR(30)  NOT NULL,
    upd_id        VARCHAR(30)  NOT NULL,
    reg_dt        TIMESTAMP    NOT NULL,
    upd_dt        TIMESTAMP    NOT NULL,
    reg_ip        VARCHAR(45)  NOT NULL,
    upd_ip        VARCHAR(45)  NOT NULL,
    CONSTRAINT pk_quick_link PRIMARY KEY (quick_link_id)
);
COMMENT ON TABLE  quick_link IS '자주찾는 서비스(사용자 메인 바로가기 버튼)';
COMMENT ON COLUMN quick_link.quick_link_id IS '바로가기 ID';
COMMENT ON COLUMN quick_link.name IS '버튼 이름(화면에 보이는 글자, 50자)';
COMMENT ON COLUMN quick_link.link_url IS '이동 주소 — /로 시작하는 사이트 안 경로 또는 http(s):// 주소만(서비스가 검사)';
COMMENT ON COLUMN quick_link.icon IS '아이콘 키(프론트 MenuGlyph 레지스트리, 메뉴 아이콘과 같은 목록). 없으면 기본 그림';
COMMENT ON COLUMN quick_link.target_yn IS '새 창으로 열기(Y/N)';
COMMENT ON COLUMN quick_link.display_yn IS '메인 노출(Y/N) — N이면 메인에서만 빠지고 순서 자리는 지킨다';
COMMENT ON COLUMN quick_link.sort_no IS '순서(▲▼ 교환으로만 바꾼다)';
COMMENT ON COLUMN quick_link.use_yn IS '사용여부(N=삭제)';

