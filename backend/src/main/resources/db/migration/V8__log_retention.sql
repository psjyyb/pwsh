-- =====================================================================
-- V8 — CMS 1.2.24 흡수: 로그 보관 일수가 실제로 동작하게
--
-- config.del_log_days는 화면에서 저장만 되고 아무 데서도 쓰이지 않았다(설명도 "로그 보관 수"라 일수인지
-- 건수인지 불분명). 이제 매일 새벽 배치(EventLogService.purgeExpiredLogs)가 이 일수가 지난 활동로그·
-- 로그인 이력을 지운다. 스키마 변경은 없다 — 설명과 값만 맞춘다.
-- =====================================================================

COMMENT ON COLUMN config.del_log_days IS
    '로그 보관 일수 — 지난 활동로그(event_log)·로그인 이력(login_log)을 배치가 지운다. 0/NULL=정리 안 함, 하한 365일. 개인정보 접근로그·파기 이력은 대상 아님';

-- 하한(365일)보다 짧게 들어가 있던 값은 하한으로 올린다. 지금까지는 아무 효과가 없던 값이라 올려도
-- 바뀌는 동작이 없고, 그대로 두면 화면에는 30이 보이는데 실제로는 365일로 도는 어긋남이 생긴다.
UPDATE config SET del_log_days = 365 WHERE del_log_days > 0 AND del_log_days < 365;
