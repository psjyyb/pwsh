-- ── 배치 실행 이력 ──
-- append-only(종료 시각·결과만 한 번 채운다). 보관은 로그 보관 정리가 같은 일수로 지운다(법정 보존 대상 아님).
CREATE TABLE IF NOT EXISTS batch_log (
    batch_log_id INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    job_cd       VARCHAR(30)   NOT NULL,
    manual_yn    VARCHAR(1)    NOT NULL DEFAULT 'N',
    status_cd    VARCHAR(20)   NOT NULL,
    result_msg   VARCHAR(1000),
    start_dt     TIMESTAMP     NOT NULL DEFAULT NOW(),
    end_dt       TIMESTAMP,
    reg_id       VARCHAR(30),
    reg_ip       VARCHAR(45),
    CONSTRAINT pk_batch_log PRIMARY KEY (batch_log_id)
);
COMMENT ON TABLE  batch_log IS '배치 실행 이력';
COMMENT ON COLUMN batch_log.manual_yn IS 'Y=관리자 즉시 실행(reg_id=누른 사람), N=예약 실행(reg_id=system)';
COMMENT ON COLUMN batch_log.status_cd IS '결과(code BATCH00): 실행 중/성공/실패';
COMMENT ON COLUMN batch_log.result_msg IS '처리 건수 요약 또는 실패 사유';
CREATE INDEX IF NOT EXISTS ix_batch_log_job ON batch_log (job_cd, batch_log_id);
CREATE INDEX IF NOT EXISTS ix_batch_log_start ON batch_log (start_dt);
-- ★ 한 작업은 동시에 한 번만 돈다 — 즉시 실행과 예약 실행이 겹치면 회원 라이프사이클이 안내메일을 두 번 보낸다.
--   "실행 중" 행을 작업당 하나로 묶어 두 번째 시작을 DB가 거절하게 한다(INSERT ... ON CONFLICT DO NOTHING).
CREATE UNIQUE INDEX IF NOT EXISTS ux_batch_log_running ON batch_log (job_cd) WHERE status_cd = 'BATCH01';

