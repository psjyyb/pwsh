ALTER TABLE config ADD COLUMN IF NOT EXISTS admin_otp_yn VARCHAR(1) NOT NULL DEFAULT 'N';
COMMENT ON COLUMN config.admin_otp_yn IS
    '관리자 2차 인증(Y/N) — 관리자는 비밀번호 다음에 메일 코드를 넣어야 로그인된다. 잠겼을 때: UPDATE config SET admin_otp_yn = ''N''';

-- 비밀번호를 통과한 관리자에게 보낸 코드. 화면은 otp_key(추측할 수 없는 난수)만 들고 다니고 코드는 해시로만 둔다.
-- 수명이 몇 분이라 이력 테이블이 아니다 — 같은 관리자가 다시 로그인하거나 하루가 지나면 지운다(LoginOtp_SQL).
CREATE TABLE IF NOT EXISTS login_otp (
    login_otp_id INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    otp_key      VARCHAR(64) NOT NULL,
    member_id    VARCHAR(30) NOT NULL,
    code_hash    TEXT        NOT NULL,
    fail_cnt     INTEGER     NOT NULL DEFAULT 0,
    expire_dt    TIMESTAMP   NOT NULL,
    use_yn       VARCHAR(1)  NOT NULL DEFAULT 'Y',
    reg_dt       TIMESTAMP   NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_login_otp PRIMARY KEY (login_otp_id),
    CONSTRAINT ux_login_otp_key UNIQUE (otp_key)
);
COMMENT ON TABLE  login_otp IS '관리자 2차 인증 코드(발송 후 몇 분만 유효)';
COMMENT ON COLUMN login_otp.code_hash IS '6자리 코드의 BCrypt 해시(평문 저장 안 함)';
COMMENT ON COLUMN login_otp.fail_cnt IS '이 코드로 틀린 횟수 — 5회면 use_yn=N(맞는 코드도 거절)';
COMMENT ON COLUMN login_otp.use_yn IS 'N=사용 완료·폐기';

