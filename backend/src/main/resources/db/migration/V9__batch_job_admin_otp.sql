-- ── 배치 작업 ──
-- 행은 코드(BatchService)에 구현된 작업과 1:1이다. 화면에서 추가·삭제하지 않으므로 use_yn(논리삭제)을 두지 않고,
-- 자동 실행 켜고 끄기는 auto_yn으로 따로 둔다(끄면 스케줄러에서만 빠지고 즉시 실행은 된다).
CREATE TABLE IF NOT EXISTS batch_job (
    batch_job_id INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    job_cd       VARCHAR(30)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    description  VARCHAR(500),
    cron_expr    VARCHAR(100) NOT NULL,
    auto_yn      VARCHAR(1)   NOT NULL DEFAULT 'Y',
    sort_no      INTEGER,
    reg_id       VARCHAR(30)  NOT NULL,
    upd_id       VARCHAR(30)  NOT NULL,
    reg_dt       TIMESTAMP    NOT NULL,
    upd_dt       TIMESTAMP    NOT NULL,
    reg_ip       VARCHAR(45)  NOT NULL,
    upd_ip       VARCHAR(45)  NOT NULL,
    CONSTRAINT pk_batch_job PRIMARY KEY (batch_job_id),
    CONSTRAINT ux_batch_job_cd UNIQUE (job_cd)
);
COMMENT ON TABLE  batch_job IS '배치 작업(주기·자동 실행). 행 = BatchService에 구현된 작업';
COMMENT ON COLUMN batch_job.job_cd IS '작업 코드(BatchService가 이 값으로 실행할 코드를 고른다)';
COMMENT ON COLUMN batch_job.cron_expr IS 'Spring cron 6자리(초 분 시 일 월 요일). 1분보다 잦게는 저장되지 않는다';
COMMENT ON COLUMN batch_job.auto_yn IS '자동 실행(Y/N). N이면 스케줄러에서 빠진다(즉시 실행은 가능)';

