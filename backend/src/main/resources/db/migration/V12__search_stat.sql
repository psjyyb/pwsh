-- =====================================================================
-- V12 — 검색 통계 · 인기 검색어 (CMS 1.2.38 흡수, CMS의 V16과 같다)
--
-- 통합검색을 할 때마다 날짜·검색어별 횟수만 쌓는다(사용자 결정 — 누가 검색했는지(회원·IP)는 남기지 않아 개인정보·보관기한 부담이 없다).
-- 관리자 > 시스템관리 > 검색 통계에서 순위·결과 없던 검색어·일별 합계를 보고, 인기 검색어에 내보이면 안 되는 말을 숨긴다.
-- 인기 검색어는 이 집계에서 뽑되 금칙어(banword)가 든 말·숨긴 말은 뺀다.
-- =====================================================================

-- ── 날짜·검색어별 집계 ──
-- 검색어는 앞뒤 공백 제거·연속 공백 하나·소문자로 정리해 넣는다(대소문자·공백만 다른 말이 따로 세지지 않게).
-- 이력 컬럼이 없다 — 누가 검색했는지를 남기지 않는 것이 이 표의 원칙이다.
CREATE TABLE IF NOT EXISTS search_keyword_daily (
    stat_date  DATE         NOT NULL,
    keyword    VARCHAR(100) NOT NULL,
    search_cnt INTEGER      NOT NULL DEFAULT 0,
    zero_cnt   INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_search_keyword_daily PRIMARY KEY (stat_date, keyword)
);
COMMENT ON TABLE  search_keyword_daily IS '검색 통계 — 날짜·검색어별 통합검색 횟수(검색한 사람은 남기지 않는다)';
COMMENT ON COLUMN search_keyword_daily.keyword IS '정리한 검색어(앞뒤 공백 제거·연속 공백 하나·소문자, 100자까지)';
COMMENT ON COLUMN search_keyword_daily.search_cnt IS '그날 통합검색 횟수(유형별 탭 이동은 세지 않는다)';
COMMENT ON COLUMN search_keyword_daily.zero_cnt IS '그중 결과가 0건이었던 횟수(콘텐츠가 비는 곳·오타를 찾는 단서)';

-- ── 인기 검색어에서 숨긴 말 ──
-- 금칙어는 아니지만 내보이면 안 되는 말(사람 이름·연락처 등)을 관리자가 통계 화면에서 숨긴다. 풀면 use_yn='N'.
CREATE TABLE IF NOT EXISTS search_keyword_hide (
    hide_id  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    keyword  VARCHAR(100) NOT NULL,
    use_yn   VARCHAR(1)   NOT NULL DEFAULT 'Y',
    reg_id   VARCHAR(30)  NOT NULL,
    upd_id   VARCHAR(30)  NOT NULL,
    reg_dt   TIMESTAMP    NOT NULL,
    upd_dt   TIMESTAMP    NOT NULL,
    reg_ip   VARCHAR(45)  NOT NULL,
    upd_ip   VARCHAR(45)  NOT NULL,
    CONSTRAINT pk_search_keyword_hide PRIMARY KEY (hide_id)
);
COMMENT ON TABLE  search_keyword_hide IS '인기 검색어에서 숨긴 말(관리자 지정, 정리한 검색어 기준)';
CREATE UNIQUE INDEX IF NOT EXISTS ux_search_keyword_hide ON search_keyword_hide (keyword) WHERE use_yn = 'Y';

