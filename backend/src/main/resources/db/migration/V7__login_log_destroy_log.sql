-- ▼ backfill — 이 테이블이 생기기 전에 파기된 계정을 채운다(DestroyLogTest가 이 아래만 따로 실행한다).
-- 근거는 event_log의 MEMBER_DESTROY: 수행자가 사람이면 관리자 즉시 파기, 비었거나 system이면 자동.
-- 근거 행이 없으면 추측하지 않고 '유형 미확인'으로 둔다. 이미 이력이 있는 계정은 건너뛴다(두 번 돌려도 한 줄).
INSERT INTO destroy_log (member_id, destroy_cd, withdraw_dt, actor_id, reg_dt, reg_ip)
SELECT m.member_id,
       CASE WHEN e.event_log_id IS NULL THEN 'DESTROY09'
            WHEN e.member_id IS NULL OR e.member_id = 'system' THEN 'DESTROY01'
            ELSE 'DESTROY02' END,
       m.withdraw_dt,
       CASE WHEN e.member_id IS NULL OR e.member_id = 'system' THEN NULL ELSE e.member_id END,
       m.destroy_dt,
       e.reg_ip
FROM member m
LEFT JOIN LATERAL (
    SELECT l.event_log_id, l.member_id, l.reg_ip FROM event_log l
    WHERE l.event_cd = 'MEMBER_DESTROY' AND l.target_id = m.member_id
    ORDER BY l.event_log_id DESC LIMIT 1
) e ON TRUE
WHERE m.destroy_dt IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM destroy_log d WHERE d.member_id = m.member_id);
