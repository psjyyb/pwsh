-- ── 로그인 이력 ──
CREATE TABLE IF NOT EXISTS login_log (
    login_log_id  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    login_id      VARCHAR(50)  NOT NULL,
    result_cd     VARCHAR(20)  NOT NULL,
    fail_message  VARCHAR(500),
    device_type   VARCHAR(20),
    user_agent    TEXT,
    reg_dt        TIMESTAMP    NOT NULL DEFAULT NOW(),
    reg_ip        VARCHAR(45),
    CONSTRAINT pk_login_log PRIMARY KEY (login_log_id)
);
COMMENT ON TABLE  login_log IS '로그인 이력(성공·실패, append-only)';
COMMENT ON COLUMN login_log.login_id IS '입력한 아이디 그대로(없는 아이디도 남긴다 — 계정 추측 공격 분석용). 50자에서 자른다';
COMMENT ON COLUMN login_log.result_cd IS '결과(code LOGIN00): 성공/비밀번호 불일치/없는 아이디/잠김/정지/휴면/IP 차단/기타';
COMMENT ON COLUMN login_log.fail_message IS '실패 시 사용자에게 나간 안내문(몇 번째 실패인지 등)';
-- 화면은 최근 순 + 기간 조회가 기본이고, 아이디로 한 사람의 시도를 모아 본다
CREATE INDEX IF NOT EXISTS ix_login_log_reg_dt ON login_log (reg_dt);
CREATE INDEX IF NOT EXISTS ix_login_log_login_id ON login_log (login_id);

-- ── 개인정보 파기 이력 ──
-- member_id를 평문으로 둔다 — 파기해도 member.member_id는 남기는 구조라(과거 글·모집의 작성자 키)
-- 이 이력이 새로 드러내는 정보는 없다.
CREATE TABLE IF NOT EXISTS destroy_log (
    destroy_log_id INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    member_id      VARCHAR(30) NOT NULL,
    destroy_cd     VARCHAR(20) NOT NULL,
    withdraw_dt    TIMESTAMP,
    actor_id       VARCHAR(30),
    reg_dt         TIMESTAMP   NOT NULL DEFAULT NOW(),
    reg_ip         VARCHAR(45),
    CONSTRAINT pk_destroy_log PRIMARY KEY (destroy_log_id)
);
COMMENT ON TABLE  destroy_log IS '개인정보 파기 이력(append-only)';
COMMENT ON COLUMN destroy_log.destroy_cd IS '파기 유형(code DESTROY00): 자동(보존기간 경과)/관리자 즉시/기존 파기(유형 미확인)';
COMMENT ON COLUMN destroy_log.withdraw_dt IS '탈퇴 시각(보존기간 계산 근거). 탈퇴 전 즉시 파기면 NULL';
COMMENT ON COLUMN destroy_log.actor_id IS '처리자(관리자 즉시 파기). 자동 파기는 NULL';
CREATE INDEX IF NOT EXISTS ix_destroy_log_reg_dt ON destroy_log (reg_dt);

