-- 파기: event_log에 MEMBER_DESTROY 한 줄만 있어 자동인지 관리자 처리인지, 언제 탈퇴한 계정인지를
--   따로 맞춰 봐야 했다. 되돌릴 수 없는 처리라 전용 이력을 둔다.
--
-- 둘 다 append-only(수정·삭제 없음)라 use_yn·upd_* 컬럼을 두지 않는다(event_log와 같은 형태).
-- 테이블·코드·채우기는 CMS의 V8과 같다. 메뉴만 이 저장소 방식(menu_id를 시퀀스에 맡김)으로 넣는다.
