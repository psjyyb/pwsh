-- V13 — 검색 동의어 (CMS 1.2.39, CMS의 V17과 같다)
--
-- 관리자가 묶어 둔 말(예: 회원가입·가입·sign up)은 서로 바꿔 가며 찾는다. 사용자 결정: 검색어 "전체"가 묶음의 한 말과 같을 때만
-- (다른 말이 붙은 검색어는 그대로) — 결과가 예측 가능하고 쿼리가 가볍다. 이 저장소는 취미·모집·게시글·페이지 네 유형 모두에 적용한다.
-- 한 행 = 한 묶음. 말은 정리(앞뒤 공백 제거·연속 공백 하나·소문자)·중복 제거 뒤 쉼표로 이어 저장한다. 한 말은 한 묶음에만 둔다(서비스가 막는다).
-- =====================================================================

CREATE TABLE IF NOT EXISTS search_synonym (
    synonym_id INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    words      VARCHAR(1000) NOT NULL,
    use_yn     VARCHAR(1)    NOT NULL DEFAULT 'Y',
    reg_id     VARCHAR(30)   NOT NULL,
    upd_id     VARCHAR(30)   NOT NULL,
    reg_dt     TIMESTAMP     NOT NULL,
    upd_dt     TIMESTAMP     NOT NULL,
    reg_ip     VARCHAR(45)   NOT NULL,
    upd_ip     VARCHAR(45)   NOT NULL,
    CONSTRAINT pk_search_synonym PRIMARY KEY (synonym_id)
);
COMMENT ON TABLE  search_synonym IS '검색 동의어 묶음(한 행 = 한 묶음). 검색어 전체가 묶음의 한 말과 같으면 묶음 전체로 찾는다';
COMMENT ON COLUMN search_synonym.words IS '정리한 말들(공백·대소문자 정리, 중복 제거), 쉼표로 구분 — 2~20개, 한 말은 한 묶음에만';

